import AppKit

/// `NSPasteboard.general` üzerinde değişiklikleri izler.
///
/// CPU optimizasyonu: Pano içeriği HİÇBİR ZAMAN her tikte okunmaz; yalnızca
/// tamsayı karşılaştırması olan `changeCount` kontrol edilir (nanosaniyeler sürer).
/// Timer'a yüksek `tolerance` verilir — macOS bu sayede tetiklemeleri diğer sistem
/// işleriyle hizalayıp (timer coalescing) işlemciyi uyku modunda daha uzun tutar.
final class PasteboardMonitor {
    enum Capture {
        case text(String)
        case image(Data)
    }

    var onCapture: ((Capture) -> Void)?

    private var timer: Timer?
    private var lastChangeCount: Int = NSPasteboard.general.changeCount

    /// Parola yöneticileri gibi kaynaklardan gelen hassas/geçici içerikler kaydedilmez.
    /// (http://nspasteboard.org standardı)
    private static let skippedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.check()
        }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Panoya kendi yazdığımız içeriğin tekrar geçmişe eklenmesini önler:
    /// yazma işleminden hemen sonra çağrılır ve sayaç senkronlanır.
    func syncChangeCount() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        guard pasteboard.availableType(from: Self.skippedTypes) == nil else { return }

        // Önce görsel: tarayıcıdan resim kopyalandığında pano hem resmi hem de
        // URL metnini içerir; kullanıcının beklediği resimdir.
        if let imageData = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
            onCapture?(.image(imageData))
            return
        }

        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            onCapture?(.text(string))
        }
    }
}
